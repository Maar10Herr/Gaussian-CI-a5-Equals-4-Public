#!/usr/bin/env python3
"""Export untrusted finite input data for Lean's independent kernel checks.

The exporter is not a verifier. Lean checks only the stated supplied row counts,
24-bit bounds, countermodel-mask agreement, and ten-face membership. This module
does not prove row validity, distinctness, exhaustive catalogue enumeration, or
Gaussian realizability.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import runpy


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "formalization/GaussianCI/Generated.lean"


def masks(rows: tuple[str, ...]) -> list[int]:
    return sorted(sum((character == "0") << i for i, character in enumerate(row))
                  for row in rows)


def lean_list(values: list[int]) -> str:
    lines = [", ".join(str(value) for value in values[i:i + 10])
             for i in range(0, len(values), 10)]
    return "[\n    " + ",\n    ".join(lines) + "\n  ]"


def source() -> str:
    catalogue = runpy.run_path(str(ROOT / "independent/catalogue.py"))
    gaussoid_rows, t4_rows, _excluded_rows = catalogue["build_catalogues"]()
    bits = (ROOT / "certificates/cycle_rule_t4_countermodel.txt").read_text().strip()
    if len(bits) != 80 or any(character not in "01" for character in bits):
        raise ValueError("countermodel certificate must contain exactly 80 bits")
    countermodel_mask = sum((character == "1") << i for i, character in enumerate(bits))
    return f'''module

public import GaussianCI.Finite

/-!
# Supplied four-variable catalogue data

Generated by `python3 formalization/tools/export_finite.py` from the current
`independent/catalogue.py`. Python supplies input data only. The finite facts
below are accepted by Lean kernel reduction, independently of Python execution.

The theorems establish supplied row counts, 24-bit bounds, agreement with the
countermodel mask, and membership of its ten faces. Row validity, distinctness,
exhaustive enumeration, Gaussian realizability, and the four-variable
classification are not proved here. The countermodel's actual axioms and
Gaussian face realizations are checked separately in `Finite.lean` and
`FaceWitnesses.lean`; they do not depend on these catalogue data.
-/

@[expose] public section

namespace GaussianCI

set_option maxRecDepth 100000
set_option maxHeartbeats 0

def suppliedFourGaussoidMasks : List Nat := {lean_list(masks(gaussoid_rows))}

def suppliedFourT4Masks : List Nat := {lean_list(masks(t4_rows))}

def suppliedCycleCountermodelMask : Nat := {countermodel_mask}

theorem suppliedCycleCountermodelMask_agrees :
    suppliedCycleCountermodelMask = cycleCountermodelMask := by decide +kernel

theorem suppliedFourGaussoidMasks_length : suppliedFourGaussoidMasks.length = 679 := by
  decide +kernel

theorem suppliedFourT4Masks_length : suppliedFourT4Masks.length = 629 := by
  decide +kernel

theorem suppliedFourGaussoidMasks_are_24_bit :
    suppliedFourGaussoidMasks.all (· < 2 ^ 24) = true := by decide +kernel

theorem suppliedFourT4Masks_are_24_bit :
    suppliedFourT4Masks.all (· < 2 ^ 24) = true := by decide +kernel

/-- Encode a four-variable face in the same local atom order as the catalogue. -/
def countermodelFaceMask (omitted : Nat) (conditioned : Bool) : Nat :=
  ((elementaryAtoms (faceVariables omitted)).zipIdx).foldl
    (fun mask (atom, index) =>
      if faceHas cycleCountermodelHas omitted conditioned atom.1 atom.2.1 atom.2.2
      then mask + 2 ^ index else mask) 0

theorem cycleCountermodel_faces_in_supplied_t4 :
    fourFaces.all (fun (omitted, conditioned) =>
      suppliedFourT4Masks.contains (countermodelFaceMask omitted conditioned)) = true := by
  decide +kernel

#print axioms suppliedFourGaussoidMasks_length
#print axioms suppliedFourT4Masks_length
#print axioms suppliedFourGaussoidMasks_are_24_bit
#print axioms suppliedFourT4Masks_are_24_bit
#print axioms cycleCountermodel_faces_in_supplied_t4

end GaussianCI
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check deterministic export")
    arguments = parser.parse_args()
    expected = source()
    if arguments.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit("Generated.lean differs from the deterministic export")
        print("finite_export_ok")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
